/**
 * HK-FE-UI-02 — (re)generates this workstream's lane in scripts-dev/meals-boundary-scan.cjs.
 *
 * The scan requires every file changed after the integration checkpoint to be explained by a registered lane. This lane is
 * PRESENTATION ONLY, so the script derives the explanation from what the diff against the pinned baseline actually contains:
 * files this workstream ADDED are `owned`; files it MODIFIED are `shared` with a reason naming the surface. It never edits
 * any other lane and never touches a check. Re-run after each phase:
 *
 *   node scripts-dev/ui02-register-lane.mjs <phase label>
 *
 * The block between the BEGIN/END markers is the only text it rewrites.
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const BASELINE = 'ccdcffcf2da254deb4c80e62d8839016fa3ebca1';
const SCAN = new URL('./meals-boundary-scan.cjs', import.meta.url);
const BEGIN = '  // BEGIN HK-FE-UI-02 LANE (generated by scripts-dev/ui02-register-lane.mjs)';
const END = '  // END HK-FE-UI-02 LANE';
const phase = process.argv[2] ?? 'presentation migration';

const lf = (text) => text.split(String.fromCharCode(13)).join('');
const diff = lf(execSync(`git diff --name-status ${BASELINE} --`, { encoding: 'utf8', maxBuffer: 1 << 26 }))
  .split('\n').filter(Boolean).map((line) => line.split('\t'));
const untracked = lf(execSync('git ls-files --others --exclude-standard', { encoding: 'utf8' })).split('\n').filter(Boolean);

const SELF = 'scripts-dev/meals-boundary-scan.cjs';
const changed = new Map();
for (const [status, file] of diff) changed.set(file, status);
for (const file of untracked) changed.set(file, 'A');
changed.delete(SELF);
// the temporary router-free evidence entry is never part of the change
for (const temp of ['evidence-entry.js']) changed.delete(temp);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\/]/g, (c) => '\\' + c);
const added = [...changed].filter(([, s]) => s === 'A').map(([f]) => f).sort();
const modified = [...changed].filter(([, s]) => s !== 'A').map(([f]) => f).sort();

const surface = (file) => {
  if (file.startsWith('src/design/')) return 'design-system token values or shared presentation primitive';
  if (file.startsWith('app/')) return 'route presentation';
  if (file.startsWith('src/features/')) return `${file.split('/')[2]} feature presentation`;
  if (file.startsWith('tests/')) return 'test updated to the new palette or structure, never weakened';
  if (file.startsWith('docs/')) return 'design documentation and supersession note';
  if (file.startsWith('scripts-dev/')) return 'design tooling';
  return 'presentation support';
};

const lines = [
  BEGIN,
  '  {',
  `    id: 'HK-FE-UI-02 (Dusty Mauve + Luxury Black design system, ${phase})',`,
  '    // Presentation-only design migration. No schema, sync kind, auth, RevenueCat, consent or persistence change.',
  '    branch: null,',
  '    owned: [',
  ...added.map((f) => `      /^${escapeRe(f)}$/,`),
  '    ],',
  '    migrations: [], schemas: [], rootCollections: [], syncKinds: [],',
  '    shared: [',
  ...modified.map((f) => `      [${JSON.stringify(f)}, ${JSON.stringify(`HK-FE-UI-02 presentation-only: ${surface(f)}`)}],`),
  `      [${JSON.stringify(SELF)}, "HK-FE-UI-02: register the design lane without weakening any check"],`,
  '    ],',
  '  },',
  END,
];

let source = lf(readFileSync(SCAN, 'utf8'));
const block = lines.join('\n');
if (source.includes(BEGIN)) {
  const start = source.indexOf(BEGIN);
  const stop = source.indexOf(END) + END.length;
  source = source.slice(0, start) + block + source.slice(stop);
} else {
  const anchor = '\n\n];\n\n/**\n * Files Feature 08 (Meals) itself must never change';
  if (!source.includes(anchor)) throw new Error('lane anchor not found');
  source = source.replace(anchor, `\n${block}\n\n];\n\n/**\n * Files Feature 08 (Meals) itself must never change`);
}
writeFileSync(SCAN, source);
console.log(`registered ${added.length} owned, ${modified.length + 1} shared`);
