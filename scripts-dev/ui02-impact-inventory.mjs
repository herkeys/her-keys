/**
 * HK-FE-UI-02 Phase 0 — design impact inventory generator.
 *
 * Walks app/ and src/, and for every .tsx/.ts file that touches the design system reports:
 *   - which token families it reads (canonical `color.*`, flat `colors.*`, `typography`/`type`, brand, ai, status)
 *   - whether it carries hard-coded colour literals (hex / rgba)
 *   - whether it is REACHABLE from an expo-router route (static import graph from app/**)
 *   - whether it has Platform-specific styles
 *
 * Output: docs/design-system/HK-FE-UI-02-impact-inventory.generated.md (a table), plus a JSON summary on stdout.
 * Presentation-only: this script reads source, writes one doc, touches nothing else.
 *
 * Usage: node scripts-dev/ui02-impact-inventory.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const toPosix = (p) => p.replaceAll('\\', '/');

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return e.name === 'node_modules' ? [] : walk(p);
    return /\.(tsx?|mjs)$/.test(e.name) && !e.name.endsWith('.d.ts') ? [p] : [];
  });
}

const files = [...walk(join(ROOT, 'app')), ...walk(join(ROOT, 'src'))];
const source = new Map(files.map((f) => [f, readFileSync(f, 'utf8')]));

const EXTS = ['.tsx', '.ts', '/index.tsx', '/index.ts'];
function resolveImport(from, spec) {
  if (!spec.startsWith('.')) return null;
  const base = resolve(dirname(from), spec);
  for (const ext of ['', ...EXTS]) {
    const candidate = resolve(base + ext);
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return null;
}

const importsOf = (file) => {
  const text = source.get(file) ?? '';
  const specs = [...text.matchAll(/(?:from|import)\s*\(?\s*['"](\.[^'"]+)['"]/g)].map((m) => m[1]);
  return specs.map((s) => resolveImport(file, s)).filter(Boolean);
};

const reachable = new Set();
const queue = files.filter((f) => toPosix(f).includes('/app/'));
while (queue.length) {
  const f = queue.pop();
  if (reachable.has(f)) continue;
  reachable.add(f);
  for (const next of importsOf(f)) if (source.has(next)) queue.push(next);
}

function classify(file, text) {
  const rel = toPosix(relative(ROOT, file));
  const uses = [];
  if (/\bcolor\.(brand)\b/.test(text)) uses.push('brand');
  if (/\bcolor\.ai\b/.test(text)) uses.push('ai');
  if (/\bcolor\.(action|status|text|surface|border|neutral)\b/.test(text)) uses.push('color.*');
  if (/\bcolors\.[a-zA-Z]+/.test(text)) uses.push('colors.* (legacy flat)');
  if (/\b(typography|type)\.[a-zA-Z]+|variant="/.test(text)) uses.push('type');
  const hard = [...text.matchAll(/#[0-9A-Fa-f]{3,8}\b|rgba?\(/g)].length;
  const platform = /Platform\.(OS|select)/.test(text);
  const designImporter = /design\/(tokens|components)|from ['"]\.\.?\/(components|tokens)['"]/.test(text) || rel.startsWith('src/design/');
  return { rel, uses, hard, platform, designImporter, reachable: reachable.has(file) || rel.startsWith('src/design/') && reachable.has(file) };
}

const rows = files
  .map((f) => classify(f, source.get(f)))
  .filter((r) => r.uses.length || r.hard || r.designImporter);

const group = (r) => {
  if (r.rel.startsWith('src/design/')) return '0 design system core';
  if (r.rel.startsWith('app/')) return '1 routes';
  const m = r.rel.match(/^src\/features\/([^/]+)/);
  return m ? `2 feature: ${m[1]}` : '3 other src';
};

const grouped = new Map();
for (const r of rows) {
  const g = group(r);
  grouped.set(g, [...(grouped.get(g) ?? []), r]);
}

let md = `# HK-FE-UI-02 — generated impact inventory\n\n`;
md += `Generated by \`scripts-dev/ui02-impact-inventory.mjs\` from the pinned baseline. Do not hand-edit; re-run the script.\n\n`;
md += `Reachability is a static import graph from \`app/**\` (expo-router mounts every file under app/). A file that is not\nreachable is not currently mounted and is recorded, not migrated.\n\n`;
md += `Totals: ${rows.length} design-touching files; ${rows.filter((r) => r.reachable).length} reachable; ${rows.filter((r) => !r.reachable).length} unreachable; ${rows.filter((r) => r.hard).length} with hard-coded colour literals; ${rows.filter((r) => r.platform).length} with Platform-specific code.\n\n`;

for (const [name, list] of [...grouped.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  md += `## ${name.slice(2)} (${list.length})\n\n| File | Token families | Hard-coded colours | Platform code | Reachable |\n|---|---|---|---|---|\n`;
  for (const r of list.sort((a, b) => a.rel.localeCompare(b.rel))) {
    md += `| \`${r.rel}\` | ${r.uses.join(', ') || '(components only)'} | ${r.hard || '—'} | ${r.platform ? 'yes' : '—'} | ${r.reachable ? 'yes' : '**no**'} |\n`;
  }
  md += `\n`;
}

writeFileSync(join(ROOT, 'docs/design-system/HK-FE-UI-02-impact-inventory.generated.md'), md);
console.log(JSON.stringify({
  files: rows.length,
  reachable: rows.filter((r) => r.reachable).length,
  unreachable: rows.filter((r) => !r.reachable).map((r) => r.rel),
  hardCoded: rows.filter((r) => r.hard).map((r) => `${r.rel}:${r.hard}`),
  brandUsers: rows.filter((r) => r.uses.includes('brand')).map((r) => r.rel),
  aiUsers: rows.filter((r) => r.uses.includes('ai')).map((r) => r.rel),
  legacyFlat: rows.filter((r) => r.uses.some((u) => u.startsWith('colors.'))).length,
}, null, 2));
